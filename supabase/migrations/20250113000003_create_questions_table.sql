-- 創建 questions 表格
-- 用於存儲解剖學問答題目

CREATE TABLE IF NOT EXISTS questions (
    id SERIAL PRIMARY KEY,
    question TEXT NOT NULL,
    options JSONB NOT NULL, -- 存儲選項數組
    correct_answer INTEGER NOT NULL, -- 正確答案的索引 (0-3)
    level INTEGER NOT NULL, -- 題目等級 (1-20)
    category VARCHAR(100) NOT NULL, -- 題目類別
    difficulty VARCHAR(20) DEFAULT 'medium', -- 難度等級
    explanation TEXT, -- 題目解釋
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 創建索引
CREATE INDEX IF NOT EXISTS idx_questions_level ON questions(level);
CREATE INDEX IF NOT EXISTS idx_questions_category ON questions(category);
CREATE INDEX IF NOT EXISTS idx_questions_difficulty ON questions(difficulty);

-- 添加註釋
COMMENT ON TABLE questions IS '解剖學問答題目表';
COMMENT ON COLUMN questions.question IS '題目內容';
COMMENT ON COLUMN questions.options IS '選項數組，格式：["選項1", "選項2", "選項3", "選項4"]';
COMMENT ON COLUMN questions.correct_answer IS '正確答案索引，0-3 對應選項1-4';
COMMENT ON COLUMN questions.level IS '題目等級，1-20';
COMMENT ON COLUMN questions.category IS '題目類別，如：循環系統、神經系統等';
COMMENT ON COLUMN questions.difficulty IS '難度等級：easy, medium, hard';
COMMENT ON COLUMN questions.explanation IS '題目解釋說明';

